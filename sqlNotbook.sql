-- Intermediate Problem 1:
-- Calculate the number of orders per month in 2018.

SELECT
    EXTRACT(MONTH FROM order_purchase_timestamp) AS month,
    COUNT(*) AS order_count
FROM orders
WHERE order_purchase_timestamp >= '2018-01-01'
  AND order_purchase_timestamp < '2019-01-01'
GROUP BY EXTRACT(MONTH FROM order_purchase_timestamp)
ORDER BY month;


-- ---------------------------------------------------------
-- Intermediate Problem 2:
-- Find the average number of products per order,
-- grouped by customer city.

WITH products_per_order AS (
    SELECT
        o.order_id,
        o.customer_id,
        COUNT(oi.order_item_id) AS product_count
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    GROUP BY o.order_id, o.customer_id
)

SELECT
    c.customer_city,
    AVG(ppo.product_count) AS average_products_per_order
FROM products_per_order ppo
JOIN customers c
    ON ppo.customer_id = c.customer_id
GROUP BY c.customer_city
ORDER BY average_products_per_order DESC;


-- ---------------------------------------------------------

-- Intermediate Problem 3:
-- Calculate the percentage of total revenue contributed
-- by each product category.

WITH category_revenue AS (
    SELECT
        p."product category" AS product_category,
        SUM(oi.price) AS revenue
    FROM order_items oi
    JOIN products p
        ON oi.product_id = p.product_id
    GROUP BY p."product category"
)

SELECT
    product_category,
    revenue,
    ROUND(
        100.0 * revenue / SUM(revenue) OVER (),
        2
    ) AS revenue_percentage
FROM category_revenue
ORDER BY revenue DESC;


-- ---------------------------------------------------------
-- Intermediate Problem 4:
-- Identify the correlation between product price and the
-- number of times a product has been purchased.

WITH product_purchase_data AS (
    SELECT
        product_id,
        AVG(price) AS product_price,
        COUNT(*) AS times_purchased
    FROM order_items
    GROUP BY product_id
)

SELECT
    CORR(product_price, times_purchased) AS correlation
FROM product_purchase_data;


-- ---------------------------------------------------------
-- Intermediate Problem 5:
-- Calculate the total revenue generated by each seller,
-- and rank them by revenue.

WITH seller_revenue AS (
    SELECT
        seller_id,
        SUM(price) AS total_revenue
    FROM order_items
    GROUP BY seller_id
)

SELECT
    seller_id,
    total_revenue,
    RANK() OVER (
        ORDER BY total_revenue DESC
    ) AS revenue_rank
FROM seller_revenue
ORDER BY revenue_rank;



