-- Advanced Problem 1:
-- Calculate the moving average of order values for each
-- customer over their order history.

WITH order_values AS (
    SELECT
        o.order_id,
        o.customer_id,
        o.order_purchase_timestamp,
        SUM(oi.price) AS order_value
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    GROUP BY
        o.order_id,
        o.customer_id,
        o.order_purchase_timestamp
)

SELECT
    order_id,
    customer_id,
    order_purchase_timestamp,
    order_value,
    AVG(order_value) OVER (
        PARTITION BY customer_id
        ORDER BY order_purchase_timestamp
        ROWS BETWEEN 1 PRECEDING AND CURRENT ROW
    ) AS moving_average
FROM order_values
ORDER BY customer_id, order_purchase_timestamp;


-- ---------------------------------------------------------
-- Advanced Problem 2:
-- Calculate the cumulative sales per month for each year.

WITH monthly_sales AS (
    SELECT
        EXTRACT(YEAR FROM o.order_purchase_timestamp) AS year,
        EXTRACT(MONTH FROM o.order_purchase_timestamp) AS month,
        SUM(oi.price) AS monthly_sales
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    GROUP BY
        EXTRACT(YEAR FROM o.order_purchase_timestamp),
        EXTRACT(MONTH FROM o.order_purchase_timestamp)
)

SELECT
    year,
    month,
    monthly_sales,
    SUM(monthly_sales) OVER (
        PARTITION BY year
        ORDER BY month
    ) AS cumulative_sales
FROM monthly_sales
ORDER BY year, month;


-- ---------------------------------------------------------
-- Advanced Problem 3:
-- Calculate the year-over-year growth rate of total sales.

WITH yearly_sales AS (
    SELECT
        EXTRACT(YEAR FROM o.order_purchase_timestamp) AS year,
        SUM(oi.price) AS total_sales
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    GROUP BY EXTRACT(YEAR FROM o.order_purchase_timestamp)
),

yearly_sales_with_previous AS (
    SELECT
        year,
        total_sales,
        LAG(total_sales) OVER (
            ORDER BY year
        ) AS previous_year_sales
    FROM yearly_sales
)

SELECT
    year,
    total_sales,
    previous_year_sales,
    ROUND(
        100.0 * (total_sales - previous_year_sales)
        / NULLIF(previous_year_sales, 0),
        2
    ) AS yoy_growth_rate
FROM yearly_sales_with_previous
ORDER BY year;


-- ---------------------------------------------------------
-- Advanced Problem 4:
-- Calculate the retention rate of customers, defined as the
-- percentage of customers who make another purchase within
-- 6 months of their first purchase.

WITH first_purchase AS (
    SELECT
        customer_id,
        MIN(order_purchase_timestamp) AS first_purchase_date
    FROM orders
    GROUP BY customer_id
),

retained_customers AS (
    SELECT DISTINCT
        fp.customer_id
    FROM first_purchase fp
    JOIN orders o
        ON fp.customer_id = o.customer_id
    WHERE o.order_purchase_timestamp > fp.first_purchase_date
      AND o.order_purchase_timestamp <=
          fp.first_purchase_date + INTERVAL '6 months'
)

SELECT
    ROUND(
        100.0 * COUNT(rc.customer_id)
        / COUNT(fp.customer_id),
        2
    ) AS retention_rate
FROM first_purchase fp
LEFT JOIN retained_customers rc
    ON fp.customer_id = rc.customer_id;


-- ---------------------------------------------------------
-- Advanced Problem 5:
-- Identify the top 3 customers who spent the most money
-- in each year.

WITH customer_yearly_spending AS (
    SELECT
        o.customer_id,
        EXTRACT(YEAR FROM o.order_purchase_timestamp) AS year,
        SUM(oi.price) AS total_spent
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    GROUP BY
        o.customer_id,
        EXTRACT(YEAR FROM o.order_purchase_timestamp)
),

ranked_customers AS (
    SELECT
        customer_id,
        year,
        total_spent,
        RANK() OVER (
            PARTITION BY year
            ORDER BY total_spent DESC
        ) AS spending_rank
    FROM customer_yearly_spending
)

SELECT
    year,
    customer_id,
    total_spent,
    spending_rank
FROM ranked_customers
WHERE spending_rank <= 3
ORDER BY year, spending_rank;